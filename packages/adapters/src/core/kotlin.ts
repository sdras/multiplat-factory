import {
  CORE_ABI_VERSION as ABI_VERSION,
  CORE_WASM_FILE as CORE_WASM,
  type CoreManifest,
} from '@mpf/core'

/** Pinned pure-Java WebAssembly runtime; interpreter only in v1 (no AOT step in the build). */
export const CHICORY_VERSION = '1.7.5'
export const CHICORY_DEPENDENCY = `com.dylibso.chicory:runtime:${CHICORY_VERSION}`

/** `computeTotal` stays `computeTotal`; `2fa-setup` -> `_2faSetup`. */
export function kotlinIdent(name: string): string {
  const camel = name
    .replace(/[^A-Za-z0-9]+([A-Za-z0-9])/g, (_, c: string) => c.toUpperCase())
    .replace(/[^A-Za-z0-9_]/g, '')
  const safe = /^[0-9]/.test(camel) ? `_${camel}` : camel || 'fn'
  return KOTLIN_RESERVED.has(safe) ? `\`${safe}\`` : safe
}

const KOTLIN_RESERVED = new Set([
  'as',
  'break',
  'class',
  'continue',
  'do',
  'else',
  'false',
  'for',
  'fun',
  'if',
  'in',
  'interface',
  'is',
  'null',
  'object',
  'package',
  'return',
  'super',
  'this',
  'throw',
  'true',
  'try',
  'typealias',
  'typeof',
  'val',
  'var',
  'when',
  'while',
])

/**
 * Kotlin host on Chicory for the Android target. JSON goes through `org.json` (in the
 * platform) so the binding adds no serialization dependency; typed wrappers take and return
 * JSONObject/JSONArray/primitive values as the schema dictates. Generated; do not edit.
 */
export function kotlinBinding(manifest: CoreManifest, packageName: string): string {
  const fns = manifest.functions.map((f) => ({ ...f, ident: kotlinIdent(f.name) }))
  return `// Generated by multiplat-factory from the shared core manifest. Do not edit.
// ABI: docs/ABI.md in the factory (version ${ABI_VERSION}). Runtime: Chicory ${CHICORY_VERSION}.
package ${packageName}.core

import android.content.Context
import com.dylibso.chicory.runtime.ExportFunction
import com.dylibso.chicory.runtime.Instance
import com.dylibso.chicory.runtime.Memory
import com.dylibso.chicory.wasm.Parser
import org.json.JSONArray
import org.json.JSONObject
import org.json.JSONTokener
import java.io.InputStream

class CoreException(val code: String, message: String) : RuntimeException("$code: $message")

/**
 * One instance per process is enough: the core is deterministic and keeps no state between
 * calls. Construct with the module bytes (\`MpfCore.fromAssets(context)\` in the app,
 * \`MpfCore.fromStream(File(...).inputStream())\` in JVM tests).
 */
class MpfCore(wasmBytes: ByteArray) {
    private val instance: Instance = Instance.builder(Parser.parse(wasmBytes)).build()
    private val memory: Memory = instance.memory()
    private val alloc: ExportFunction = instance.export("mpf_alloc")
    private val free: ExportFunction = instance.export("mpf_free")
    private val callFn: ExportFunction = instance.export("mpf_call")
    private val manifestFn: ExportFunction = instance.export("mpf_manifest")

    init {
        val version = instance.export("mpf_abi_version").apply()[0].toInt()
        require(version == ${ABI_VERSION}) { "core ABI version $version; this host speaks ${ABI_VERSION}" }
    }

    private fun write(s: String): Pair<Int, Int> {
        val bytes = s.toByteArray(Charsets.UTF_8)
        val ptr = alloc.apply(bytes.size.toLong())[0].toInt()
        memory.write(ptr, bytes)
        return ptr to bytes.size
    }

    private fun take(packed: Long): String {
        val ptr = (packed ushr 32).toInt()
        val len = (packed and 0xffff_ffffL).toInt()
        val s = String(memory.readBytes(ptr, len), Charsets.UTF_8)
        free.apply(ptr.toLong(), len.toLong())
        return s
    }

    /** The manifest the module was built with. */
    fun manifest(): JSONObject = JSONObject(take(manifestFn.apply()[0]))

    /** Call any core function by manifest name; \`input\` is any JSON value (JSONObject, JSONArray, primitive, or JSONObject.NULL). */
    fun call(name: String, input: Any?): Any? {
        val (namePtr, nameLen) = write(name)
        val (reqPtr, reqLen) = write(toJson(input))
        val response: JSONObject
        try {
            response = JSONObject(take(callFn.apply(namePtr.toLong(), nameLen.toLong(), reqPtr.toLong(), reqLen.toLong())[0]))
        } finally {
            free.apply(namePtr.toLong(), nameLen.toLong())
            free.apply(reqPtr.toLong(), reqLen.toLong())
        }
        if (!response.getBoolean("ok")) {
            val err = response.getJSONObject("error")
            throw CoreException(err.optString("code", "internal"), err.optString("message", "unknown error"))
        }
        return response.opt("value")
    }

${fns.map((f) => `    /** ${f.description.replace(/\*\//g, '* /') || f.name} */\n    fun ${f.ident}(input: Any?): Any? = call(${JSON.stringify(f.name)}, input)`).join('\n\n')}

    companion object {
        const val ASSET = "${CORE_WASM}"

        fun fromStream(stream: InputStream): MpfCore = stream.use { MpfCore(it.readBytes()) }

        fun fromAssets(context: Context): MpfCore = fromStream(context.assets.open(ASSET))

        /** JSON text for any org.json value or Kotlin primitive. */
        fun toJson(value: Any?): String = when (value) {
            null, JSONObject.NULL -> "null"
            is JSONObject, is JSONArray -> value.toString()
            is String -> JSONObject.quote(value)
            is Boolean, is Number -> value.toString()
            is Map<*, *> -> JSONObject(value).toString()
            is Collection<*> -> JSONArray(value).toString()
            else -> JSONObject.quote(value.toString())
        }

        /** Parse JSON text into org.json values (JSONObject, JSONArray, String, Number, Boolean, or JSONObject.NULL). */
        fun parseJson(text: String): Any? = JSONTokener(text).nextValue()
    }
}
`
}

/**
 * JUnit test that runs every golden vector through Chicory on the JVM, no device needed.
 * Vectors and the module are read from test resources.
 */
export function kotlinParityTest(packageName: string): string {
  return `// Generated by multiplat-factory. Do not edit: vectors live in src/test/resources/core/vectors/.
package ${packageName}.core

import org.json.JSONArray
import org.json.JSONObject
import org.json.JSONTokener
import org.junit.Assert.assertTrue
import org.junit.Test

class CoreParityTest {
    private fun resource(path: String) = checkNotNull(javaClass.classLoader?.getResourceAsStream(path)) { "missing test resource $path" }

    private fun canonical(v: Any?): String = when (v) {
        null, JSONObject.NULL -> "null"
        is JSONObject -> v.keys().asSequence().sorted().joinToString(",", "{", "}") { k -> JSONObject.quote(k) + ":" + canonical(v.opt(k)) }
        is JSONArray -> (0 until v.length()).joinToString(",", "[", "]") { canonical(v.opt(it)) }
        is Number -> { val d = v.toDouble(); if (d == Math.floor(d) && !d.isInfinite() && Math.abs(d) < 1e15) d.toLong().toString() else d.toString() }
        is String -> JSONObject.quote(v)
        else -> v.toString()
    }

    @Test
    fun goldenVectorsMatchTheCore() {
        val core = MpfCore.fromStream(resource("core/${CORE_WASM}"))
        val index = String(resource("core/vectors/index.txt").readBytes()).lines().filter { it.isNotBlank() }
        val failures = mutableListOf<String>()
        var total = 0
        for (file in index) {
            val set = JSONTokener(String(resource("core/vectors/$file").readBytes())).nextValue() as JSONObject
            val function = set.getString("function")
            val vectors = set.getJSONArray("vectors")
            for (i in 0 until vectors.length()) {
                total++
                val v = vectors.getJSONObject(i)
                val id = v.optString("id", "?")
                try {
                    val actual = core.call(function, v.opt("input"))
                    val expected = v.opt("expected")
                    if (canonical(actual) != canonical(expected)) failures += "$function/$id: expected \${canonical(expected)} got \${canonical(actual)}"
                } catch (e: CoreException) {
                    failures += "$function/$id: error \${e.code}: \${e.message}"
                }
            }
        }
        assertTrue("\${failures.size} of $total vectors failed:\\n" + failures.joinToString("\\n"), failures.isEmpty())
    }
}
`
}
