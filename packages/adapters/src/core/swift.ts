/**
 * Swift host on WasmKit for the iOS target. JSON goes through Foundation's JSONSerialization
 * (fragments allowed) so the binding adds no dependency beyond WasmKit. Generated; do not edit.
 */
export function swiftBinding(manifest: CoreManifest): string {
  const fns = manifest.functions.map((f) => ({ ...f, ident: swiftIdent(f.name) }))
  return `// Generated by multiplat-factory from the shared core manifest. Do not edit.
// ABI: docs/ABI.md in the factory (version ${ABI_VERSION}). Runtime: WasmKit ${WASMKIT_VERSION}.
import Foundation
import WasmKit

public struct CoreError: Error, CustomStringConvertible {
    public let code: String
    public let message: String
    public var description: String { "\\(code): \\(message)" }
}

/// One instance per process is enough: the core is deterministic and keeps no state between
/// calls. Not thread-safe; call from one queue (the main actor in the app).
public final class MpfCore {
    public static let resourceName = "${CORE_WASM.replace(/\.wasm$/, '')}"

    private let instance: Instance
    private let memory: Memory
    private let allocFn: Function
    private let freeFn: Function
    private let callFn: Function
    private let manifestFn: Function

    public init(wasm: Data) throws {
        let engine = Engine()
        let store = Store(engine: engine)
        let module = try parseWasm(bytes: [UInt8](wasm))
        instance = try module.instantiate(store: store)
        guard let memory = instance.exports[memory: "memory"],
              let allocFn = instance.exports[function: "mpf_alloc"],
              let freeFn = instance.exports[function: "mpf_free"],
              let callFn = instance.exports[function: "mpf_call"],
              let manifestFn = instance.exports[function: "mpf_manifest"],
              let versionFn = instance.exports[function: "mpf_abi_version"]
        else { throw CoreError(code: "abi", message: "module lacks an ABI export") }
        self.memory = memory
        self.allocFn = allocFn
        self.freeFn = freeFn
        self.callFn = callFn
        self.manifestFn = manifestFn
        guard case .i32(${ABI_VERSION}) = try versionFn([])[0] else {
            throw CoreError(code: "abi", message: "unexpected core ABI version; this host speaks ${ABI_VERSION}")
        }
    }

    /// The module bundled with the app (or a test bundle).
    public static func bundled(_ bundle: Bundle = .main) throws -> MpfCore {
        guard let url = bundle.url(forResource: resourceName, withExtension: "wasm") else {
            throw CoreError(code: "abi", message: "\\(resourceName).wasm is not in bundle \\(bundle.bundlePath)")
        }
        return try MpfCore(wasm: try Data(contentsOf: url))
    }

    private func write(_ bytes: [UInt8]) throws -> (ptr: UInt32, len: UInt32) {
        guard case .i32(let ptr) = try allocFn([.i32(UInt32(bytes.count))])[0] else {
            throw CoreError(code: "abi", message: "mpf_alloc returned a non-i32")
        }
        memory.withUnsafeMutableBufferPointer(offset: UInt(ptr), count: bytes.count) { buffer in
            bytes.withUnsafeBytes { buffer.copyMemory(from: $0) }
        }
        return (ptr, UInt32(bytes.count))
    }

    private func take(_ packed: Value) throws -> Data {
        guard case .i64(let v) = packed else { throw CoreError(code: "abi", message: "expected a packed i64") }
        let ptr = UInt32(truncatingIfNeeded: v >> 32)
        let len = Int(UInt32(truncatingIfNeeded: v & 0xffff_ffff))
        let data = memory.withUnsafeBufferPointer(offset: UInt(ptr), count: len) { Data($0) }
        _ = try freeFn([.i32(ptr), .i32(UInt32(len))])
        return data
    }

    /// The manifest the module was built with.
    public func manifest() throws -> [String: Any] {
        let data = try take(try manifestFn([])[0])
        return (try JSONSerialization.jsonObject(with: data)) as? [String: Any] ?? [:]
    }

    /// Call any core function by manifest name. \`input\` is any JSON value (dictionary, array,
    /// string, number, bool, or NSNull); the result is the same family of values.
    public func call(_ name: String, _ input: Any) throws -> Any {
        let nameBytes = [UInt8](name.utf8)
        let request = [UInt8](try JSONSerialization.data(withJSONObject: input, options: [.fragmentsAllowed]))
        let n = try write(nameBytes)
        let r = try write(request)
        defer {
            _ = try? freeFn([.i32(n.ptr), .i32(n.len)])
            _ = try? freeFn([.i32(r.ptr), .i32(r.len)])
        }
        let response = try take(try callFn([.i32(n.ptr), .i32(n.len), .i32(r.ptr), .i32(r.len)])[0])
        guard let envelope = try JSONSerialization.jsonObject(with: response, options: [.fragmentsAllowed]) as? [String: Any] else {
            throw CoreError(code: "abi", message: "response is not an envelope")
        }
        if envelope["ok"] as? Bool == true {
            return envelope["value"] ?? NSNull()
        }
        let err = envelope["error"] as? [String: Any] ?? [:]
        throw CoreError(code: err["code"] as? String ?? "internal", message: err["message"] as? String ?? "unknown error")
    }

${fns.map((f) => `    /// ${f.description.replace(/\n/g, ' ') || f.name}\n    public func ${f.ident}(_ input: Any) throws -> Any { try call(${JSON.stringify(f.name)}, input) }`).join('\n\n')}
}
`
}

/** XCTest that runs every golden vector through WasmKit on the simulator; vectors are test-bundle resources. */
export function swiftParityTest(moduleName: string): string {
  return `// Generated by multiplat-factory. Do not edit: vectors live in the test bundle's core-vectors resources.
import Foundation
import XCTest
@testable import ${moduleName}

final class CoreParityTests: XCTestCase {
    private func canonical(_ value: Any) throws -> String {
        let data = try JSONSerialization.data(withJSONObject: value, options: [.sortedKeys, .fragmentsAllowed])
        return String(decoding: data, as: UTF8.self)
    }

    func testGoldenVectorsMatchTheCore() throws {
        let bundle = Bundle(for: CoreParityTests.self)
        let core = try MpfCore.bundled(bundle)
        guard let indexURL = bundle.url(forResource: "index", withExtension: "txt") else {
            return XCTFail("core-vectors index.txt is not in the test bundle")
        }
        let files = try String(contentsOf: indexURL, encoding: .utf8).split(separator: "\\n").map(String.init).filter { !$0.isEmpty }
        var failures: [String] = []
        var total = 0
        for file in files {
            let name = file.hasSuffix(".json") ? String(file.dropLast(5)) : file
            guard let url = bundle.url(forResource: name, withExtension: "json") else {
                failures.append("\\(file): missing from the test bundle")
                continue
            }
            let set = try JSONSerialization.jsonObject(with: try Data(contentsOf: url)) as? [String: Any] ?? [:]
            let function = set["function"] as? String ?? name
            for vector in set["vectors"] as? [[String: Any]] ?? [] {
                total += 1
                let id = vector["id"] as? String ?? "?"
                let expected = vector["expected"] ?? NSNull()
                do {
                    let actual = try core.call(function, vector["input"] ?? NSNull())
                    if try canonical(actual) != canonical(expected) {
                        failures.append("\\(function)/\\(id): expected \\(try canonical(expected)) got \\(try canonical(actual))")
                    }
                } catch let error as CoreError {
                    failures.append("\\(function)/\\(id): error \\(error)")
                }
            }
        }
        XCTAssertTrue(failures.isEmpty, "\\(failures.count) of \\(total) vectors failed:\\n" + failures.joined(separator: "\\n"))
    }
}
`
}
