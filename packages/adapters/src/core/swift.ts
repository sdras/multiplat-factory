/** Pure-Swift WebAssembly interpreter; iOS forbids JIT and JavaScriptCore has no WebAssembly. */
export const WASMKIT_VERSION = '0.4.0'
export const WASMKIT_URL = 'https://github.com/swiftwasm/WasmKit.git'

/** `computeTotal` stays `computeTotal`; `2fa-setup` -> `_2faSetup`. */
export function swiftIdent(name: string): string {
  const camel = name
    .replace(/[^A-Za-z0-9]+([A-Za-z0-9])/g, (_, c: string) => c.toUpperCase())
    .replace(/[^A-Za-z0-9_]/g, '')
  const safe = /^[0-9]/.test(camel) ? `_${camel}` : camel || 'fn'
  return SWIFT_RESERVED.has(safe) ? `\`${safe}\`` : safe
}

