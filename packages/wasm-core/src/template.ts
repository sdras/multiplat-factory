import { CORE_ABI_VERSION, CORE_WASM_FILE, type CoreFunction, type CoreManifest } from '@mpf/core'

/** Fixed crate and library name: hosts look for `mpf_core.wasm` and call `mpf_core::api::dispatch`. */
export const CORE_CRATE = 'mpf_core'
export const CORE_WASM = CORE_WASM_FILE
export const ABI_VERSION = CORE_ABI_VERSION

export const CORE_VERSIONS = {
  edition: '2021',
  serde: '1',
  serdeJson: '1',
} as const

export interface CoreProject {
  appName: string
  functions: CoreFunction[]
}

/** `computeTotal` -> `compute_total`; `2fa` -> `f_2fa`. Rust identifiers only. */
export function rustIdent(name: string): string {
  const snake = name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9_]+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
    .toLowerCase()
  const safe = /^[0-9]/.test(snake) ? `f_${snake}` : snake
  return RESERVED.has(safe) ? `${safe}_` : safe || 'f'
}

