export function manifestFor(p: CoreProject): CoreManifest {
  return {
    abiVersion: ABI_VERSION,
    functions: p.functions.map((f) => ({
      name: f.name,
      description: f.description,
      inputSchema: f.inputSchema,
      outputSchema: f.outputSchema,
    })),
  }
}

/**
 * The crate as written before any LLM touches it. It builds, exposes the ABI, and dispatches
 * every planned function to a stub that answers `unimplemented`, so `cargo build` and the
 * ABI glue are never the worker's problem.
 */
export function coreFiles(p: CoreProject): Record<string, string> {
  const files: Record<string, string> = {}
  const fns = p.functions.map((f) => ({ ...f, ident: rustIdent(f.name) }))
  const seen = new Set<string>()
  for (const f of fns) {
    if (seen.has(f.ident)) throw new Error(`two core functions map to the Rust module ${f.ident}`)
    seen.add(f.ident)
  }

  files['Cargo.toml'] = `[package]
name = "${CORE_CRATE}"
version = "0.1.0"
edition = "${CORE_VERSIONS.edition}"
publish = false

[lib]
crate-type = ["cdylib", "rlib"]

[dependencies]
serde = { version = "${CORE_VERSIONS.serde}", features = ["derive"] }
serde_json = "${CORE_VERSIONS.serdeJson}"

[profile.release]
panic = "abort"
opt-level = "z"
lto = true
codegen-units = 1
strip = true

[profile.dev]
panic = "abort"
`

  files['manifest.json'] = `${JSON.stringify(manifestFor(p), null, 2)}\n`

  files['src/lib.rs'] = `//! Shared core for ${p.appName}, generated by multiplat-factory.
//!
//! The ABI (docs/ABI.md in the factory) is implemented here and must not change:
//! hosts on every platform call \`mpf_call\` with a function name and a JSON request
//! and read back a JSON envelope. Business logic lives in \`api/\`.

pub mod api;

use serde::Serialize;
use serde_json::{json, Value};

/// An error the core reports instead of panicking. Codes are stable strings.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct CoreError {
    pub code: String,
    pub message: String,
}

impl CoreError {
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        Self { code: code.to_string(), message: message.into() }
    }
    pub fn invalid_input(message: impl Into<String>) -> Self {
        Self::new("invalid_input", message)
    }
}

impl From<serde_json::Error> for CoreError {
    fn from(e: serde_json::Error) -> Self {
        CoreError::invalid_input(e.to_string())
    }
}

pub type CoreResult = Result<Value, CoreError>;

/// Manifest embedded at scaffold time; edit \`manifest.json\` when a function's schema changes.
pub const MANIFEST: &str = include_str!("../manifest.json");

/// Run a function by name on a JSON request and produce the response envelope.
pub fn call_json(name: &str, request: &str) -> String {
    let response = match serde_json::from_str::<Value>(request) {
        Ok(input) => match api::dispatch(name, input) {
            Ok(value) => json!({ "ok": true, "value": value }),
            Err(e) => json!({ "ok": false, "error": e }),
        },
        Err(e) => json!({ "ok": false, "error": CoreError::invalid_input(format!("request is not JSON: {e}")) }),
    };
    response.to_string()
}

// ---- ABI exports (see docs/ABI.md) ----

#[no_mangle]
pub extern "C" fn mpf_abi_version() -> i32 {
    ${ABI_VERSION}
}

#[no_mangle]
pub extern "C" fn mpf_alloc(len: i32) -> *mut u8 {
    let mut buf: Vec<u8> = Vec::with_capacity(len.max(0) as usize);
    let ptr = buf.as_mut_ptr();
    std::mem::forget(buf);
    ptr
}

/// # Safety
/// \`ptr\`/\`len\` must come from \`mpf_alloc\` or from a block this module returned.
#[no_mangle]
pub unsafe extern "C" fn mpf_free(ptr: *mut u8, len: i32) {
    if ptr.is_null() {
        return;
    }
    let len = len.max(0) as usize;
    drop(Vec::from_raw_parts(ptr, len, len));
}

fn leak(bytes: Vec<u8>) -> i64 {
    // Capacity must equal length so mpf_free can rebuild the Vec exactly.
    let mut exact: Vec<u8> = Vec::with_capacity(bytes.len());
    exact.extend_from_slice(&bytes);
    let len = exact.len() as i64;
    let ptr = exact.as_mut_ptr() as i64;
    std::mem::forget(exact);
    (ptr << 32) | (len & 0xffff_ffff)
}

/// # Safety
/// The four arguments describe two valid UTF-8 byte ranges inside this module's memory.
#[no_mangle]
pub unsafe extern "C" fn mpf_call(name_ptr: *const u8, name_len: i32, req_ptr: *const u8, req_len: i32) -> i64 {
    let name = std::str::from_utf8(std::slice::from_raw_parts(name_ptr, name_len.max(0) as usize)).unwrap_or("");
    let req = std::str::from_utf8(std::slice::from_raw_parts(req_ptr, req_len.max(0) as usize)).unwrap_or("null");
    leak(call_json(name, req).into_bytes())
}

#[no_mangle]
pub extern "C" fn mpf_manifest() -> i64 {
    leak(MANIFEST.as_bytes().to_vec())
}
`

  files['src/api/mod.rs'] =
    `//! One module per core function. \`dispatch\` is the only entry point the ABI uses.
use crate::{CoreError, CoreResult};
use serde_json::Value;

${fns.map((f) => `pub mod ${f.ident};`).join('\n')}

/// Route a request to a function by its manifest name.
pub fn dispatch(name: &str, input: Value) -> CoreResult {
    match name {
${fns.map((f) => `        ${JSON.stringify(f.name)} => ${f.ident}::call(input),`).join('\n')}
        _ => Err(CoreError::new("unknown_function", format!("no core function named {name}"))),
    }
}
`

  for (const f of fns) {
    files[`src/api/${f.ident}.rs`] = `//! ${f.name}: ${f.description.replace(/\n/g, ' ')}
//! Source symbols: ${f.sourceSymbols.join(', ') || 'n/a'}
//!
//! Input schema:  ${JSON.stringify(f.inputSchema)}
//! Output schema: ${JSON.stringify(f.outputSchema)}
use crate::{CoreError, CoreResult};
use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Input {
    // TODO: fields from the input schema
}

#[derive(Debug, Serialize)]
pub struct Output {
    // TODO: fields from the output schema
}

pub fn call(input: Value) -> CoreResult {
    let _req: Input = serde_json::from_value(input)?;
    Err(CoreError::new("unimplemented", "${f.name} is not implemented yet"))
}
`
  }

  files['tests/vectors.rs'] =
    `//! Golden vectors: every file in vectors/ is asserted through the same dispatch the ABI uses.
use serde_json::Value;
use std::fs;
use std::path::Path;

#[test]
fn golden_vectors() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("vectors");
    let mut failures: Vec<String> = Vec::new();
    let mut total = 0usize;
    if let Ok(entries) = fs::read_dir(&dir) {
        let mut files: Vec<_> = entries.flatten().map(|e| e.path()).filter(|p| p.extension().map(|x| x == "json").unwrap_or(false)).collect();
        files.sort();
        for file in files {
            let set: Value = serde_json::from_str(&fs::read_to_string(&file).expect("read vector file")).expect("vector file is JSON");
            let function = set["function"].as_str().expect("function name").to_string();
            for v in set["vectors"].as_array().expect("vectors array") {
                total += 1;
                let id = v["id"].as_str().unwrap_or("?");
                match mpf_core::api::dispatch(&function, v["input"].clone()) {
                    Ok(actual) if actual == v["expected"] => {}
                    Ok(actual) => failures.push(format!("{function}/{id}: expected {} got {}", v["expected"], actual)),
                    Err(e) => failures.push(format!("{function}/{id}: error {}: {}", e.code, e.message)),
                }
            }
        }
    }
    assert!(failures.is_empty(), "{} of {} vectors failed:\\n{}", failures.len(), total, failures.join("\\n"));
}
`

  files['vectors/.gitkeep'] = ''

  files['MPF.md'] = `# Conventions for this shared core

- Rust crate \`${CORE_CRATE}\`, built for \`wasm32-unknown-unknown\` with **no imports**: no clock, randomness, locale, file, or network access. Anything time- or locale-dependent is an explicit input.
- \`src/lib.rs\` is the ABI and is not yours to change. Implement functions in \`src/api/<name>.rs\` and keep \`api::dispatch\` routing every manifest name.
- Each function takes one JSON object and returns one JSON value (\`CoreResult\`). Validate input and return \`CoreError::invalid_input\`; never panic (\`panic = "abort"\` kills the host instance).
- \`manifest.json\` lists every function with JSON Schemas for input and output. Keep it accurate; host bindings on every platform are generated from it.
- Golden vectors in \`vectors/<function>.json\` are the acceptance tests: \`cargo test\` must pass. Add vectors for edge cases you discover in the source.
- Build: \`cargo build --release --target wasm32-unknown-unknown\`. Test: \`cargo test\`.
- Serialization must match the source app's wire formats byte for byte (field names, number formats, ordering where it matters).
`

  return files
}
